// Builds src/pages/twin/ui/hmi/ix-scoped.css from @siemens/ix's core stylesheet: only the design tokens (custom
// properties), with global selectors (:root, body, :host) re-scoped to `.hx` — the SCADA / HMI container. iX
// components (shadow DOM) read these tokens; iX's global element styles (body, p, h1…, a, inputs, scrollbars) are
// left out so the rest of the app keeps its own look.
//
// Run after upgrading @siemens/ix:  node scripts/twin/build-ix-scoped-css.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const app = path.resolve(here, '../..')
// the package's exports do not list package.json: resolve its directory through node_modules
const ixPkg = path.join(app, 'node_modules/@siemens/ix')
const css = readFileSync(path.join(ixPkg, 'dist/siemens-ix/siemens-ix-core.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')

const GLOBAL = /^(:root|:root body|body|html|:host|:root,\s*:host)$/

/** split top-level rules, descending into @media / @supports blocks */
function rules(text) {
  const out = []
  let i = 0
  while (i < text.length) {
    const open = text.indexOf('{', i)
    if (open < 0) break
    const head = text.slice(i, open).trim()
    let depth = 1
    let j = open + 1
    while (j < text.length && depth) {
      if (text[j] === '{') depth++
      else if (text[j] === '}') depth--
      j++
    }
    const body = text.slice(open + 1, j - 1)
    if (head.startsWith('@media') || head.startsWith('@supports')) out.push({ at: head, rules: rules(body) })
    else if (!head.startsWith('@')) out.push({ sel: head, body })
    i = j
  }
  return out
}

/** split declarations on `;` outside strings and parentheses (values hold data URIs and font lists) */
function tokens(body) {
  const out = []
  let cur = ''
  let quote = ''
  let depth = 0
  for (const ch of body) {
    if (quote) {
      if (ch === quote) quote = ''
    } else if (ch === '"' || ch === "'") quote = ch
    else if (ch === '(') depth++
    else if (ch === ')') depth--
    else if (ch === ';' && depth === 0) {
      out.push(cur.trim())
      cur = ''
      continue
    }
    cur += ch
  }
  if (cur.trim()) out.push(cur.trim())
  return out.filter(s => s.startsWith('--'))
}

function emit(list) {
  const out = []
  for (const r of list) {
    if (r.at) {
      const inner = emit(r.rules)
      if (inner.length) out.push(`${r.at}{${inner.join('')}}`)
      continue
    }
    const decl = tokens(r.body)
    if (!decl.length) continue
    const sels = r.sel
      .split(',')
      .map(s => s.trim())
      .map(s => (GLOBAL.test(s) ? '.hx' : s.replace(/^:root\s+/, '.hx ').replace(/^body\s*/, '.hx ')))
    // theme-scoped selectors ([data-ix-theme=…]) are kept as they are; anything else global goes under .hx
    out.push(`${[...new Set(sels)].join(',')}{${decl.join(';')}}`)
  }
  return out
}

const result = emit(rules(css))
const header = `/* Generated by scripts/twin/build-ix-scoped-css.mjs from @siemens/ix ${JSON.parse(readFileSync(path.join(ixPkg, 'package.json'), 'utf8')).version} (MIT). Do not edit. */\n`
const outFile = path.join(app, 'src/pages/twin/ui/hmi/ix-scoped.css')
writeFileSync(outFile, header + result.join('\n') + '\n')
console.log(`wrote ${result.length} token rules to ${path.relative(app, outFile)}`)
