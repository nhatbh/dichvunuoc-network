/** The component catalog in the twin's panels: symbol icon, catalog identity, functions and properties. */
import { catalogCodeList, getCatalogItem, mapSymbolSVG, type Status } from '@wn/component-models'
import { For, Show } from 'solid-js'

const CODE_LIST = new Map(catalogCodeList().map(c => [c.code, c]))

export const FUNCTION_VI: Record<string, string> = {
  isolates: 'Cô lập',
  controls: 'Điều tiết',
  meters: 'Đo đếm',
  senses: 'Giám sát',
  pumps: 'Bơm',
  fireFlow: 'Chữa cháy',
  stores: 'Lưu trữ',
  supplies: 'Cấp nguồn',
  connects: 'Nối ống',
  serves: 'Khách hàng',
  treats: 'Xử lý nước',
  automates: 'Điều khiển / tự động hóa',
}
export const CATEGORY_VI: Record<string, string> = {
  Pipes: 'Ống',
  Fittings: 'Phụ kiện',
  Valves: 'Van',
  'Hydrants & services': 'Trụ cứu hỏa & dịch vụ',
  'Metering & monitoring': 'Đo đếm & giám sát',
  'Pumping & storage': 'Bơm & lưu trữ',
  Treatment: 'Xử lý nước',
  'Electrical & automation': 'Điện & tự động hóa',
}

/** The catalog's map symbol for a code (inline SVG, generated by @wn/component-models). */
export function CatalogIcon(props: { code: string; status?: Status; size?: number }) {
  // eslint-disable-next-line solid/no-innerhtml -- SVG generated from the catalog's own vector definitions
  return <span style={{ display: 'inline-flex', 'flex-shrink': 0 }} innerHTML={mapSymbolSVG(props.code, { status: props.status, size: props.size ?? 22 })} />
}

/** Catalog identity of a component: code, Vietnamese name, category, functions, size. */
export function CatalogBlock(props: { code: string; dn?: number; dn2?: number }) {
  const item = () => getCatalogItem(props.code)
  const entry = () => CODE_LIST.get(props.code)
  return (
    <Show when={item()}>
      {it => (
        <>
          <div class="tw-h">Danh mục thành phần</div>
          <div style={{ display: 'flex', gap: '8px', 'align-items': 'center' }}>
            <CatalogIcon code={props.code} size={30} />
            <div style={{ 'min-width': 0 }}>
              <div style={{ 'font-weight': 650 }}>{it().vi}</div>
              <div style={{ 'font-size': '11.5px', color: 'var(--muted)' }}>
                <code>{props.code}</code> · {CATEGORY_VI[it().category] ?? it().category}
              </div>
            </div>
          </div>
          <div class="tw-controls">
            <For each={entry()?.functions ?? []}>{f => <span class="tw-chip info">{FUNCTION_VI[f] ?? f}</span>}</For>
            <Show when={props.dn && it().dnRange[1] > 15}>
              <span class="tw-chip">
                DN{props.dn}
                {props.dn2 ? `×${props.dn2}` : ''}
              </span>
            </Show>
          </div>
        </>
      )}
    </Show>
  )
}
