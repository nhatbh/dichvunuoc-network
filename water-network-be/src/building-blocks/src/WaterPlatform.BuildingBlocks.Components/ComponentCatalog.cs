public sealed record ComponentProperty(
    string Key,
    string Type,
    double? Min = null,
    double? Max = null,
    IReadOnlyList<string>? Values = null,
    string? Unit = null);

public sealed record ComponentDefinition(
    string Code,
    string Name,
    string Vi,
    string Category,
    ComponentKind Kind,
    string Host,
    IReadOnlyList<string> Functions,
    int DefaultDn,
    IReadOnlyList<int> DnRange,
    IReadOnlyList<ComponentProperty> Properties)
{
    public bool Does(string function) => Functions.Contains(function, StringComparer.Ordinal);
}

/// <summary>
/// The platform component catalog. The list is generated by <c>@wn/component-models</c>
/// (the authority for component codes) and embedded in this assembly.
/// </summary>
public interface IComponentCatalog
{
    IReadOnlyCollection<ComponentDefinition> All { get; }

    /// <summary>The definition, or null for an unknown code (codes are case-insensitive; the result is canonical).</summary>
    ComponentDefinition? Find(string? code);

    /// <summary>The definition; throws <see cref="DomainException"/> for an unknown code or another kind.</summary>
    ComponentDefinition Require(string? code, ComponentKind? kind = null);

    /// <summary>Problems with an asset's properties: unknown keys, wrong types, out-of-range values.</summary>
    IReadOnlyList<string> ValidateProperties(string code, IReadOnlyDictionary<string, string>? properties);

    /// <summary>
    /// The catalog properties in a draft's attribute bag (CAD import, editor, design drafts): keys the
    /// component declares. Attributes no component declares (provenance, the code itself, a pipe's
    /// diameterMm/material columns) are not properties.
    /// </summary>
    IReadOnlyDictionary<string, string> PropertiesIn(string code, IReadOnlyDictionary<string, string>? attributes);

    /// <summary>
    /// Problems with a draft's attribute bag: invalid declared properties, and properties of other
    /// components (e.g. a setpoint on a gate valve) which would otherwise be dropped silently.
    /// </summary>
    IReadOnlyList<string> ValidateAttributes(string code, IReadOnlyDictionary<string, string>? attributes);
}

public sealed class ComponentCatalog : IComponentCatalog
{
    private static readonly Lazy<ComponentCatalog> Embedded = new(Load);
    private static readonly JsonSerializerOptions JsonOptions =
        new(JsonSerializerDefaults.Web) { Converters = { new JsonStringEnumConverter() } };
    private readonly FrozenDictionary<string, ComponentDefinition> _byCode;

    public ComponentCatalog(IEnumerable<ComponentDefinition> definitions)
    {
        _byCode = definitions.ToFrozenDictionary(d => d.Code, StringComparer.OrdinalIgnoreCase);
    }

    /// <summary>The embedded catalog.</summary>
    public static IComponentCatalog Default => Embedded.Value;

    public IReadOnlyCollection<ComponentDefinition> All => _byCode.Values;

    public ComponentDefinition? Find(string? code)
        => string.IsNullOrWhiteSpace(code) ? null : _byCode.GetValueOrDefault(code.Trim());

    public ComponentDefinition Require(string? code, ComponentKind? kind = null)
    {
        var definition = Find(code)
            ?? throw new DomainException("Component.Unknown",
                $"'{code}' is not a component code in the platform catalog.");
        if (kind is { } expected && definition.Kind != expected)
            throw new DomainException("Component.WrongKind",
                $"'{definition.Code}' is a {definition.Kind}, not a {expected}.");
        return definition;
    }

    public IReadOnlyList<string> ValidateProperties(string code, IReadOnlyDictionary<string, string>? properties)
    {
        var definition = Require(code);
        var problems = new List<string>();
        if (properties is null) return problems;
        if (properties.Count > 40) problems.Add("At most 40 properties.");
        foreach (var (key, value) in properties)
        {
            var spec = definition.Properties.FirstOrDefault(p => string.Equals(p.Key, key, StringComparison.Ordinal));
            if (spec is null)
            {
                problems.Add($"{definition.Code} has no property '{key}'.");
                continue;
            }
            if (value is null || value.Length > 200)
            {
                problems.Add($"{key}: value missing or longer than 200 characters.");
                continue;
            }
            switch (spec.Type)
            {
                case "int" when !long.TryParse(value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var i):
                    problems.Add($"{key}: '{value}' is not a whole number.");
                    break;
                case "int":
                    CheckRange(spec, long.Parse(value, CultureInfo.InvariantCulture), problems);
                    break;
                case "number" when !double.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var n) || !double.IsFinite(n):
                    problems.Add($"{key}: '{value}' is not a number.");
                    break;
                case "number":
                    CheckRange(spec, double.Parse(value, CultureInfo.InvariantCulture), problems);
                    break;
                case "enum" when spec.Values is null || !spec.Values.Contains(value, StringComparer.Ordinal):
                    problems.Add($"{key}: '{value}' is not one of {string.Join(", ", spec.Values ?? [])}.");
                    break;
            }
        }
        return problems;
    }

    // A pipe keeps diameter and material as its own fields, not as properties.
    private static readonly string[] PipeColumns = ["diameterMm", "material", "dn"];

    private HashSet<string>? _allPropertyKeys;

    public IReadOnlyDictionary<string, string> PropertiesIn(string code, IReadOnlyDictionary<string, string>? attributes)
    {
        var definition = Require(code);
        var keys = definition.Properties.Select(p => p.Key).ToHashSet(StringComparer.Ordinal);
        if (definition.Kind == ComponentKind.Pipe) keys.ExceptWith(PipeColumns);
        return (attributes ?? new Dictionary<string, string>())
            .Where(kv => keys.Contains(kv.Key))
            .ToDictionary(kv => kv.Key, kv => kv.Value, StringComparer.Ordinal);
    }

    public IReadOnlyList<string> ValidateAttributes(string code, IReadOnlyDictionary<string, string>? attributes)
    {
        var definition = Require(code);
        var declared = definition.Properties.Select(p => p.Key).ToHashSet(StringComparer.Ordinal);
        if (definition.Kind == ComponentKind.Pipe) declared.UnionWith(PipeColumns);
        _allPropertyKeys ??= _byCode.Values.SelectMany(d => d.Properties).Select(p => p.Key).ToHashSet(StringComparer.Ordinal);
        var problems = (attributes ?? new Dictionary<string, string>()).Keys
            .Where(k => !declared.Contains(k) && _allPropertyKeys.Contains(k))
            .Order(StringComparer.Ordinal)
            .Select(k => $"{definition.Code} has no property '{k}'.")
            .ToList();
        problems.AddRange(ValidateProperties(definition.Code, PropertiesIn(definition.Code, attributes)));
        return problems;
    }

    private static void CheckRange(ComponentProperty spec, double value, List<string> problems)
    {
        if ((spec.Min is { } min && value < min) || (spec.Max is { } max && value > max))
            problems.Add($"{spec.Key}: {value.ToString(CultureInfo.InvariantCulture)} is outside {spec.Min}–{spec.Max}{(spec.Unit is null ? "" : " " + spec.Unit)}.");
    }

    private static ComponentCatalog Load()
    {
        using var stream = typeof(ComponentCatalog).Assembly.GetManifestResourceStream("component-codes.json")
            ?? throw new InvalidOperationException("component-codes.json is not embedded.");
        var file = JsonSerializer.Deserialize<CodeFile>(stream, JsonOptions)
            ?? throw new InvalidOperationException("component-codes.json is empty.");
        return new ComponentCatalog(file.Codes.Select(c => new ComponentDefinition(
            c.Code, c.Name, c.Vi, c.Category, c.Kind, c.Host, c.Functions, c.DefaultDN, c.DnRange, c.Properties)));
    }

    private sealed record CodeFile(IReadOnlyList<CodeEntry> Codes);

    private sealed record CodeEntry(
        string Code,
        string Name,
        string Vi,
        string Category,
        ComponentKind Kind,
        string Host,
        IReadOnlyList<string> Functions,
        int DefaultDN,
        IReadOnlyList<int> DnRange,
        IReadOnlyList<ComponentProperty> Properties);
}
