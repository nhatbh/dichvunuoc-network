"""The platform component catalog, as this service validates block mappings against it.

`catalog_codes.json` is generated by `@wn/component-models` (`npm run codes` in
water-network-fe/packages/component-models), the authority for component codes; a test there
fails when this copy drifts. Each code says how gis-be stores the component today
(`gisKind` Pipe/Node/Device with `gisNodeType` or `gisDeviceType`); the code itself travels
with the draft as the `componentCode` attribute.
"""

from __future__ import annotations

import json
from functools import lru_cache
from importlib.resources import files


@lru_cache(maxsize=1)
def component_codes() -> dict[str, dict]:
    body = json.loads(files(__package__).joinpath("catalog_codes.json").read_text("utf-8"))
    return {entry["code"]: entry for entry in body["codes"]}


def component(code: str) -> dict | None:
    return component_codes().get(code)
