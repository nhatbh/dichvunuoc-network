"""The platform component catalog, as this service maps CAD blocks to it (decision 0028).

`catalog_codes.json` is generated by `@wn/component-models` (`npm run codes` in
water-network-fe/packages/component-models), the authority for component codes; a test there
fails when this copy drifts. Per code: the GIS asset `kind` (Node/Pipe/Device), the `host` a
device attaches to (pipe/node), functional flags and the `properties` it may carry. Drafts carry
the code as attribute `componentCode` and catalog properties as further attributes.
"""

from __future__ import annotations

import json
import math
from functools import lru_cache
from importlib.resources import files

# Block rules saved before decision 0028 named a gis-be type; they now map to a component.
LEGACY_NODE_TYPES = {
    "Junction": "Junction",
    "Reservoir": "Reservoir",
    "Tank": "Tank",
    "Hydrant": "Hydrant",
    "Other": "Junction",
}
LEGACY_DEVICE_TYPES = {
    "Valve": "GateValve",
    "FlowMeter": "BulkMeter",
    "PressureSensor": "PressureSensor",
    "Pump": "Pump",
    "Hydrant": "Hydrant",
}


@lru_cache(maxsize=1)
def component_codes() -> dict[str, dict]:
    body = json.loads(files(__package__).joinpath("catalog_codes.json").read_text("utf-8"))
    return {entry["code"]: entry for entry in body["codes"]}


@lru_cache(maxsize=1)
def _by_folded_code() -> dict[str, dict]:
    return {code.casefold(): entry for code, entry in component_codes().items()}


def component(code: str | None) -> dict | None:
    """The catalog entry for a code (case-insensitive; the entry's `code` is canonical)."""
    return _by_folded_code().get((code or "").strip().casefold())


def accepts_host(code: str | None, host_kind: str | None) -> bool:
    """Can a device of this component attach to a reviewed pipe or node?

    In-line devices sit on a pipe. Point devices sit on a node; a pipe is accepted too, and the
    device then attaches to the pipe-end node nearest to it (within the host tolerance).
    """
    entry = component(code)
    if entry is None or entry["kind"] != "Device":
        return False
    if entry["host"] == "pipe":
        return host_kind == "Pipe"
    return host_kind in {"Node", "Pipe"}


def _valid(spec: dict, value: str) -> bool:
    kind = spec["type"]
    try:
        if kind == "int":
            number = int(value)
        elif kind == "number":
            number = float(value)
            if not math.isfinite(number):
                return False
        elif kind == "enum":
            return value in spec.get("values", [])
        else:
            return len(value) <= 200
    except ValueError:
        return False
    low, high = spec.get("min"), spec.get("max")
    return (low is None or number >= low) and (high is None or number <= high)


def properties_from_block(code: str, block_attributes: dict | None) -> tuple[dict, list[str]]:
    """Catalog properties from a block's ATTRIB tags (tag matched case-insensitively to the
    property key, e.g. DN → dn). Returns the valid properties and the rejected tags."""
    entry = component(code)
    if entry is None or not block_attributes:
        return {}, []
    specs = {spec["key"].casefold(): spec for spec in entry["properties"]}
    properties, rejected = {}, []
    for tag, raw in block_attributes.items():
        spec = specs.get(str(tag).strip().casefold())
        if spec is None:
            continue
        value = str(raw).strip()
        if not value:
            continue
        if spec["type"] == "number":
            value = value.replace(",", ".")
        if _valid(spec, value):
            properties[spec["key"]] = value
        else:
            rejected.append(f"{tag}={raw}")
    return properties, rejected
